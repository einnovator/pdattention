"""Summarize matched generic and learned routing across the HF bundle catalog."""

from __future__ import annotations

import csv
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
RESULTS = (
    ROOT
    / "docs/papers/shared/results/paper4_5_runtime/hf_catalog_adapters"
)
MODELS = {
    "qwen2.5-1.5b-instruct": "Qwen2.5-1.5B-Instruct",
    "qwen2.5-coder-1.5b-instruct": "Qwen2.5-Coder-1.5B-Instruct",
    "qwen3-4b": "Qwen3-4B",
    "qwen3-4b-mlx-8bit": "Qwen3-4B 8-bit",
    "qwen3-14b": "Qwen3-14B",
    "llama3-8b": "Llama-3.1-8B",
    "gemma3-1b": "Gemma-3-1B",
}
DATASETS = ("qasper", "hotpotqa", "combined")
METRICS = ("R@20%", "MRR", "AUC0-30")


def _round(value: float) -> float:
    return round(float(value), 6)


def _recommendation(model: str) -> str:
    if model.startswith("qwen"):
        return "Learned for QASPER; generic for HotpotQA"
    if model.startswith("llama"):
        return "Learned for QASPER; generic for recall-sensitive mixed use"
    return "Learned for QASPER/mixed use; HotpotQA remains metric-dependent"


def summarize() -> dict:
    """Create a compact, public summary without per-example or per-step payloads."""

    rows = []
    models = []
    for slug, label in MODELS.items():
        source = RESULTS / slug / "comparison.json"
        raw = json.loads(source.read_text(encoding="utf-8"))
        model = {
            "slug": slug,
            "label": label,
            "base_model": raw["base_model"],
            "base_model_revision": raw["base_model_revision"],
            "selected_seed": raw["selected_seed"],
            "adapter_parameters": raw["adapter_parameters"],
            "training_examples": raw["training_examples"],
            "validation_examples": raw["validation_examples"],
            "test_examples": raw["test_examples"],
            "seeds": raw["seeds"],
            "recommendation": _recommendation(slug),
            "datasets": {},
        }
        for dataset in DATASETS:
            generic = raw["generic_baseline"][dataset]["summary"]
            learned = raw["selected_learned"][dataset]["summary"]
            metrics = {
                metric: {
                    "generic": _round(generic[metric]),
                    "learned": _round(learned[metric]),
                    "delta": _round(learned[metric] - generic[metric]),
                }
                for metric in METRICS
            }
            model["datasets"][dataset] = metrics
            sample_count = int(raw["selected_learned"][dataset]["examples"])
            for metric, values in metrics.items():
                rows.append(
                    {
                        "model": label,
                        "base_model": raw["base_model"],
                        "dataset": dataset,
                        "metric": metric,
                        **values,
                        "test_examples": sample_count,
                        "selected_seed": raw["selected_seed"],
                        "adapter_parameters": raw["adapter_parameters"],
                    }
                )
        models.append(model)

    summary = {
        "schema_version": 1,
        "protocol": "Frozen native attention-input features; generic cosine versus five-seed asymmetric linear router",
        "selection": "Best combined validation AUC0-30; test identities remain held out",
        "hardware": "NVIDIA RTX 5060 Laptop GPU and Apple M4 Pro; exact host is retained per model artifact",
        "datasets": ["QASPER", "HotpotQA"],
        "models": models,
        "conclusion": (
            "Learned routing is consistently positive on QASPER but does not transfer "
            "uniformly to HotpotQA; generic routing remains the catalog default."
        ),
    }
    RESULTS.mkdir(parents=True, exist_ok=True)
    (RESULTS / "summary.json").write_text(
        json.dumps(summary, indent=2), encoding="utf-8"
    )
    with (RESULTS / "adapter_comparison.csv").open(
        "w", newline="", encoding="utf-8"
    ) as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    _write_tex(models)
    _write_plot(models)
    return summary


def _write_tex(models: list[dict]) -> None:
    lines = [
        "% Generated by summarize_hf_catalog_adapters.py.",
        "\\begin{table*}[t]",
        "\\centering",
        "\\small",
        "\\caption{Held-out routing comparison for exact post-trained HF and quantized MLX model identities. "
        "Cohort sizes are retained in the source artifact. The learned router is selected from five "
        "seeds using validation data; $R_{20}$ is evidence recall at a 20\\% chunk budget.}",
        "\\label{tab:hf-catalog-adapters}",
        "\\begin{tabular}{lrrrrrr}",
        "\\toprule",
        "& \\multicolumn{2}{c}{QASPER $R_{20}$} & "
        "\\multicolumn{2}{c}{HotpotQA $R_{20}$} & "
        "\\multicolumn{2}{c}{Combined MRR} \\\\",
        "Model & Generic & Learned & Generic & Learned & Generic & Learned \\\\",
        "\\midrule",
    ]
    for model in models:
        qasper = model["datasets"]["qasper"]["R@20%"]
        hotpot = model["datasets"]["hotpotqa"]["R@20%"]
        combined = model["datasets"]["combined"]["MRR"]
        lines.append(
            f"{model['label']} & {qasper['generic']:.3f} & {qasper['learned']:.3f} & "
            f"{hotpot['generic']:.3f} & {hotpot['learned']:.3f} & "
            f"{combined['generic']:.3f} & {combined['learned']:.3f} \\\\"
        )
    lines.extend(["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""])
    (RESULTS / "generated_hf_catalog_adapters.tex").write_text(
        "\n".join(lines), encoding="utf-8"
    )


def _write_plot(models: list[dict]) -> None:
    import matplotlib.pyplot as plt
    import numpy as np

    labels = [model["label"] for model in models]
    x = np.arange(len(labels))
    width = 0.36
    fig, axes = plt.subplots(1, 2, figsize=(13.0, 4.2), sharey=True)
    for axis, dataset, title in zip(
        axes, ("qasper", "hotpotqa"), ("QASPER", "HotpotQA"), strict=True
    ):
        generic = [model["datasets"][dataset]["R@20%"]["generic"] for model in models]
        learned = [model["datasets"][dataset]["R@20%"]["learned"] for model in models]
        axis.bar(x - width / 2, generic, width, label="Generic cosine", color="#4472C4")
        axis.bar(x + width / 2, learned, width, label="Learned router", color="#E07A3F")
        axis.set_title(title)
        axis.set_xticks(x, labels, rotation=22, ha="right")
        axis.set_ylim(0, 0.75)
        axis.grid(axis="y", alpha=0.25)
        axis.set_axisbelow(True)
    axes[0].set_ylabel("Evidence recall at 20% chunk budget")
    axes[0].legend(frameon=False, loc="upper left")
    fig.tight_layout()
    fig.savefig(RESULTS / "adapter_recall_comparison.png", dpi=180)
    fig.savefig(RESULTS / "adapter_recall_comparison.pdf")
    plt.close(fig)


if __name__ == "__main__":
    print(json.dumps(summarize(), indent=2))
