"""Measure instrumentation overhead without conflating it with model latency."""

from __future__ import annotations

import argparse
import csv
import json
import statistics
import time
from pathlib import Path

from pra_hf.observability import (
    Observability,
    ObservabilityConfig,
    OTelConfig,
    PrometheusConfig,
)


def configuration(name: str) -> ObservabilityConfig:
    if name == "off":
        return ObservabilityConfig()
    if name == "metrics":
        return ObservabilityConfig(
            enabled=True, prometheus=PrometheusConfig(enabled=True)
        )
    if name == "sampled_otel":
        return ObservabilityConfig(
            enabled=True,
            otel=OTelConfig(
                enabled=True,
                sampler="parent_based_trace_id_ratio",
                sample_rate=0.01,
            ),
        )
    if name == "detailed_otel":
        return ObservabilityConfig(
            enabled=True,
            otel=OTelConfig(enabled=True, sampler="always_on", sample_rate=1.0),
        )
    raise ValueError(name)


def run_mode(name: str, iterations: int, repeats: int) -> dict:
    telemetry = Observability(configuration(name))
    samples = []
    attributes_evaluated = 0

    def attributes() -> dict:
        nonlocal attributes_evaluated
        attributes_evaluated += 1
        return {"pra.engine": "hf", "pra.context.selected_tokens": 64}

    try:
        for _ in range(repeats):
            started = time.perf_counter()
            for _ in range(iterations):
                with telemetry.span("pra.context.realize", attributes):
                    pass
                telemetry.increment(
                    "pra_gateway_requests_total",
                    labels={
                        "engine": "hf",
                        "execution_mode": "E2",
                        "status": "success",
                    },
                )
            samples.append(time.perf_counter() - started)
    finally:
        telemetry.close()
    return {
        "mode": name,
        "iterations": iterations,
        "repeats": repeats,
        "median_seconds": statistics.median(samples),
        "mean_seconds": statistics.mean(samples),
        "p95_seconds": sorted(samples)[max(0, int(0.95 * len(samples)) - 1)],
        "median_us_per_operation": statistics.median(samples) * 1e6 / iterations,
        "attributes_evaluated": attributes_evaluated,
        "raw_seconds": samples,
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--iterations", type=int, default=10_000)
    parser.add_argument("--repeats", type=int, default=7)
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("docs/papers/shared/results/paper4_5_runtime/observability"),
    )
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    rows = [
        run_mode(name, args.iterations, args.repeats)
        for name in ("off", "metrics", "sampled_otel", "detailed_otel")
    ]
    baseline = rows[0]["median_seconds"]
    for row in rows:
        row["overhead_ratio"] = row["median_seconds"] / baseline
    payload = {
        "scope": "instrumentation microbenchmark; not model-serving qualification",
        "primary_qualification_telemetry": "off",
        "rows": rows,
    }
    (args.output / "observability_overhead.json").write_text(
        json.dumps(payload, indent=2) + "\n", encoding="utf-8"
    )
    with (args.output / "observability_overhead.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(
            handle,
            fieldnames=("mode", "median_us_per_operation", "overhead_ratio", "attributes_evaluated"),
        )
        writer.writeheader()
        for row in rows:
            writer.writerow({key: row[key] for key in writer.fieldnames})
    lines = [
        "% Generated by experiments.paper4_5_runtime.run_observability_overhead",
        "\\begin{tabular}{lrrr}",
        "\\toprule",
        "Mode & Median $\\mu$s/op & Ratio & Attributes evaluated \\\\",
        "\\midrule",
    ]
    for row in rows:
        lines.append(
            f"{row['mode'].replace('_', ' ')} & {row['median_us_per_operation']:.3f} & "
            f"{row['overhead_ratio']:.2f}$\\times$ & {row['attributes_evaluated']} \\\\"
        )
    lines.extend(("\\bottomrule", "\\end{tabular}"))
    (args.output / "generated_observability_overhead.tex").write_text(
        "\n".join(lines) + "\n", encoding="utf-8"
    )
    print(json.dumps(payload, indent=2))


if __name__ == "__main__":
    main()
