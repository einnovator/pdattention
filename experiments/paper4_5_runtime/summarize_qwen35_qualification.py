"""Render the Qwen3.5-27B routing and end-task qualification artifacts."""

from __future__ import annotations

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
DEFAULT_RESULTS = (
    ROOT
    / "docs/papers/shared/results/paper4_5_runtime/hf_catalog_adapters/qwen3.5-27b"
)
DATASETS = ("qasper", "hotpotqa")
CONDITIONS = (
    "FULL_NO_PRA",
    "PRA_GENERIC",
    "PRA_LEARNED",
    "PRA_ORACLE_CONTROL",
)
LABELS = {
    "FULL_NO_PRA": "Full / No PRA",
    "PRA_GENERIC": "PRA generic",
    "PRA_LEARNED": "PRA learned",
    "PRA_ORACLE_CONTROL": "Oracle control",
}


def summarize(directory: Path = DEFAULT_RESULTS) -> dict:
    """Create compact JSON, LaTeX, and plots from the raw qualification rows."""

    comparison = json.loads((directory / "comparison.json").read_text(encoding="utf-8"))
    generation = json.loads(
        (directory / "end_task_qualification.json").read_text(encoding="utf-8")
    )
    aggregate = {
        (row["dataset"], row["condition"]): row for row in generation["aggregate"]
    }
    routing = {
        dataset: {
            "generic_r20": comparison["generic_baseline"][dataset]["summary"]["R@20%"],
            "learned_r20": comparison["selected_learned"][dataset]["summary"]["R@20%"],
            "generic_mrr": comparison["generic_baseline"][dataset]["summary"]["MRR"],
            "learned_mrr": comparison["selected_learned"][dataset]["summary"]["MRR"],
        }
        for dataset in DATASETS
    }
    payload = {
        "schema_version": "pra-qwen35-summary-v1",
        "model_id": generation["model_id"],
        "model_revision": generation["model_revision"],
        "selected_seed": comparison["selected_seed"],
        "adapter_parameters": comparison["adapter_parameters"],
        "training_examples": comparison["training_examples"],
        "validation_examples": comparison["validation_examples"],
        "test_examples": comparison["test_examples"],
        "routing": routing,
        "generation": generation["aggregate"],
        "native_memory_status": generation["native_memory_status"],
    }
    (directory / "qualification_summary.json").write_text(
        json.dumps(payload, indent=2) + "\n", encoding="utf-8"
    )
    _write_tables(directory, routing, aggregate)
    _write_plot(directory, routing, aggregate)
    return payload


def _write_tables(directory: Path, routing: dict, aggregate: dict) -> None:
    routing_lines = [
        "% Generated by summarize_qwen35_qualification.py.",
        "\\begin{tabular}{lrrrr}",
        "\\toprule",
        "Dataset & Generic $R_{20}$ & Learned $R_{20}$ & Generic MRR & Learned MRR \\\\",
        "\\midrule",
    ]
    for dataset in DATASETS:
        row = routing[dataset]
        routing_lines.append(
            f"{dataset.upper()} & {row['generic_r20']:.3f} & {row['learned_r20']:.3f} & "
            f"{row['generic_mrr']:.3f} & {row['learned_mrr']:.3f} \\\\"
        )
    routing_lines.extend(("\\bottomrule", "\\end{tabular}", ""))
    (directory / "generated_qwen35_routing.tex").write_text(
        "\n".join(routing_lines), encoding="utf-8"
    )

    generation_lines = [
        "% Generated by summarize_qwen35_qualification.py.",
        "\\begin{tabular}{llrrrr}",
        "\\toprule",
        "Dataset & Condition & Token F1 & Evidence recall & Visible tokens & TTFT (ms) \\\\",
        "\\midrule",
    ]
    for dataset in DATASETS:
        for condition in CONDITIONS:
            row = aggregate[(dataset, condition)]
            generation_lines.append(
                f"{dataset.upper()} & {LABELS[condition]} & {row['token_f1']:.3f} & "
                f"{row['evidence_recall']:.3f} & {row['visible_prompt_tokens']:.0f} & "
                f"{row['ttft_ms']:.0f} \\\\"
            )
    generation_lines.extend(("\\bottomrule", "\\end{tabular}", ""))
    (directory / "generated_qwen35_end_task.tex").write_text(
        "\n".join(generation_lines), encoding="utf-8"
    )


def _write_plot(directory: Path, routing: dict, aggregate: dict) -> None:
    import matplotlib.pyplot as plt
    import numpy as np

    colors = ("#4C78A8", "#F28E2B", "#59A14F", "#9C9C9C")
    fig, axes = plt.subplots(1, 3, figsize=(13.8, 4.1))

    x = np.arange(len(DATASETS))
    width = 0.34
    axes[0].bar(
        x - width / 2,
        [routing[dataset]["generic_r20"] for dataset in DATASETS],
        width,
        label="Generic",
        color=colors[0],
    )
    axes[0].bar(
        x + width / 2,
        [routing[dataset]["learned_r20"] for dataset in DATASETS],
        width,
        label="Learned",
        color=colors[1],
    )
    axes[0].set_title("Routing recall at 20%")
    axes[0].set_xticks(x, [dataset.upper() for dataset in DATASETS])
    axes[0].set_ylim(0, 1)
    axes[0].legend(frameon=False)

    offsets = np.linspace(-0.3, 0.3, len(CONDITIONS))
    for offset, condition, color in zip(offsets, CONDITIONS, colors, strict=True):
        axes[1].bar(
            x + offset,
            [aggregate[(dataset, condition)]["token_f1"] for dataset in DATASETS],
            0.19,
            label=LABELS[condition],
            color=color,
        )
    axes[1].set_title("End-task token F1")
    axes[1].set_xticks(x, [dataset.upper() for dataset in DATASETS])
    axes[1].set_ylim(0, 1)

    for offset, condition, color in zip(offsets, CONDITIONS, colors, strict=True):
        axes[2].bar(
            x + offset,
            [aggregate[(dataset, condition)]["ttft_ms"] / 1000 for dataset in DATASETS],
            0.19,
            label=LABELS[condition],
            color=color,
        )
    axes[2].set_title("Time to first token")
    axes[2].set_xticks(x, [dataset.upper() for dataset in DATASETS])
    axes[2].set_ylabel("seconds")
    axes[2].legend(frameon=False, fontsize=8)

    for axis in axes:
        axis.grid(axis="y", alpha=0.25)
        axis.set_axisbelow(True)
    fig.tight_layout()
    fig.savefig(directory / "qwen35_qualification.png", dpi=180)
    fig.savefig(directory / "qwen35_qualification.pdf")
    plt.close(fig)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--directory", type=Path, default=DEFAULT_RESULTS)
    print(json.dumps(summarize(parser.parse_args().directory), indent=2))


if __name__ == "__main__":
    main()
